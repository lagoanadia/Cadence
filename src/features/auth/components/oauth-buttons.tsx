import { oauthSignInAction } from "@/features/auth/actions";

type Props = {
  google: boolean;
  github: boolean;
};

const buttonClass =
  "flex h-11 w-full items-center justify-center gap-3 rounded-xl border border-border bg-surface text-sm font-medium hover:bg-surface-2";

/**
 * Server Component: no JavaScript is sent to the browser for these buttons.
 * `.bind(null, "google")` creates a copy of the action with its first
 * argument already filled in, so the form can call it with no arguments.
 */
export function OAuthButtons({ google, github }: Props) {
  if (!google && !github) return null;

  return (
    <div className="flex flex-col gap-3">
      {google && (
        <form action={oauthSignInAction.bind(null, "google")}>
          <button type="submit" className={buttonClass}>
            <GoogleLogo />
            Continue with Google
          </button>
        </form>
      )}
      {github && (
        <form action={oauthSignInAction.bind(null, "github")}>
          <button type="submit" className={buttonClass}>
            <GitHubLogo />
            Continue with GitHub
          </button>
        </form>
      )}
      <div className="my-2 flex items-center gap-3 text-xs text-muted">
        <span className="h-px flex-1 bg-border" />
        or with email
        <span className="h-px flex-1 bg-border" />
      </div>
    </div>
  );
}

